fn find(table: &[(u32, u32)], c: u32) -> bool {
    table
        .binary_search_by(|&(a, b)| {
            if b < c {
                std::cmp::Ordering::Less
            } else if a > c {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

fn char_width(c: char) -> usize {
    let c = c as u32;
    if find(&ZERO, c) {
        0
    } else if find(&WIDE, c) {
        2
    } else {
        1
    }
}

fn is_emoji_start(c: char, next: Option<char>) -> bool {
    char_width(c) == 2 || (next == Some('\u{FE0F}') && WITH_VS16.iter().any(|&(a, b, w)| (a..=b).contains(&(c as u32)) && w == 2))
}

/// The columns `text` takes. An emoji with a skin tone, or emoji joined by
/// U+200D, is one emoji of two columns, as `emoji-regex` finds it.
pub fn string_width(text: &str) -> usize {
    if text.bytes().all(|b| (0x20..0x80).contains(&b)) {
        return text.len();
    }
    let chars: Vec<char> = text.chars().collect();
    let mut width = 0;
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        let next = chars.get(i + 1).copied();
        if ('\u{1F1E6}'..='\u{1F1FF}').contains(&c) && next.is_some_and(|n| ('\u{1F1E6}'..='\u{1F1FF}').contains(&n)) {
            width += 2;
            i += 2;
            continue;
        }
        if is_emoji_start(c, next) {
            width += 2;
            i += 1;
            loop {
                match chars.get(i) {
                    Some('\u{FE0F}') | Some('\u{1F3FB}'..='\u{1F3FF}') => i += 1,
                    Some('\u{200D}') if chars.get(i + 1).is_some_and(|&n| is_emoji_start(n, chars.get(i + 2).copied())) => i += 2,
                    _ => break,
                }
            }
            continue;
        }
        width += char_width(c);
        i += 1;
    }
    width
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn widths_as_prettier_counts_them() {
        for (text, width) in [
            ("👍🏽", 2),
            ("👨‍👩‍👧", 2),
            ("🇮🇷", 2),
            ("1️⃣", 2),
            ("❤️", 2),
            ("✅", 2),
            ("سلام\u{200C}ها", 7),
            ("é", 1),
            ("a\u{0651}b", 3),
            ("漢字", 4),
            ("abc", 3),
        ] {
            assert_eq!(string_width(text), width, "{text}");
        }
    }
}
